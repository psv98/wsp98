export const CLUBS: ClubDef[] = RAW.map(([id, name, media, color, blurb, o], i) => {
  const strength = Math.round((BALANCE.clubs.topStrength - i * BALANCE.clubs.strengthStep) * 10) / 10;
  return {
    id, name, media, color, blurb,
    logo: `assets/clubs/${id}.png`,
    seed: i + 1,
    strength,
    attack: strength + o[0],
    defense: strength + o[1],
    passing: strength + o[2],
    discipline: 70 + o[3] * 3,
    keeper: strength + o[4],
    home: BALANCE.clubs.homeBonus + (i % 3) * 0.3,
  };
});

export const CLUB_BY_ID: Record<string, ClubDef> = Object.fromEntries(CLUBS.map((c) => [c.id, c]));
